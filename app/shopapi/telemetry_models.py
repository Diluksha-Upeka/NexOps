"""Telemetry event model — stores simulated logs, metrics, and trace spans.

Each event is tagged with a ``kind`` (log / metric / span), the originating
service and scenario, and carries its payload in a JSONB ``attributes``
column.  This keeps the schema simple while allowing different telemetry
types to share a single queryable table.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from typing import Any

from sqlalchemy import DateTime, Index, String, Text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class TelemetryEvent(Base):
    """A single telemetry observation generated by the simulator."""

    __tablename__ = "telemetry_events"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    scenario_id: Mapped[str | None] = mapped_column(
        String(100), nullable=True, doc="Scenario key that generated this event."
    )
    kind: Mapped[str] = mapped_column(String(20), nullable=False, doc="log | metric | span")
    timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=lambda: datetime.now(UTC)
    )
    service: Mapped[str] = mapped_column(String(100), nullable=False, default="shopapi")
    route: Mapped[str | None] = mapped_column(String(200), nullable=True)
    method: Mapped[str | None] = mapped_column(String(10), nullable=True)
    status_code: Mapped[int | None] = mapped_column(nullable=True)
    duration_ms: Mapped[float | None] = mapped_column(nullable=True)
    level: Mapped[str | None] = mapped_column(
        String(20), nullable=True, doc="Log level: INFO, WARNING, ERROR"
    )
    message: Mapped[str | None] = mapped_column(Text, nullable=True)
    trace_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    span_id: Mapped[str | None] = mapped_column(String(32), nullable=True)
    parent_span_id: Mapped[str | None] = mapped_column(String(32), nullable=True)
    attributes: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)

    __table_args__ = (
        Index("ix_telemetry_service_time", "service", "timestamp"),
        Index("ix_telemetry_kind_time", "kind", "timestamp"),
        Index("ix_telemetry_scenario", "scenario_id"),
    )

    def __repr__(self) -> str:
        return f"<TelemetryEvent {self.kind} {self.service} {self.timestamp}>"
